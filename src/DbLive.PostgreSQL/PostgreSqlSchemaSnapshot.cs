using DbLive.Schema;

namespace DbLive.PostgreSQL;

/// <summary>
/// The schema snapshot of PostgreSQL, read from <c>pg_catalog</c> (PostgreSQL 12 or later). Definitions come from the
/// <c>pg_get_*def</c> functions, which print them in one form; names are compared as they are, PostgreSQL derives the ones
/// it generates from the table and columns. Columns are identified by name, not by <c>attnum</c>.
/// </summary>
internal static class PostgreSqlSchemaSnapshot
{
	public const string Query = """
		with ext as (
			-- the objects of extensions: the extension is compared, not its objects.
			select d.classid, d.objid
			from pg_depend d
			where d.deptype = 'e'
		),
		nsp as (
			-- user schemas outside DbLive's own schema.
			select n.oid, n.nspname
			from pg_namespace n
			where n.nspname not in ('pg_catalog', 'information_schema', 'dblive')
			  and n.nspname not like 'pg\_toast%'
			  and n.nspname not like 'pg\_temp\_%'
			  and not exists (select 1 from ext where ext.classid = 'pg_namespace'::regclass and ext.objid = n.oid)
		),
		rel as (
			select c.oid
			     , c.relkind
			     , c.relispartition
			     , c.relpersistence
			     , c.relrowsecurity
			     , c.relpartbound
			     , c.reloptions
			     , n.nspname
			     , n.nspname || '.' || c.relname as full_name
			from pg_class c
			join nsp n on n.oid = c.relnamespace
			where not exists (select 1 from ext where ext.classid = 'pg_class'::regclass and ext.objid = c.oid)
		)

		select 'Schema' as object_type
		     , n.nspname as object_name
		     , null as parent_name
		     , '' as definition
		from nsp n

		union all

		select 'Extension'
		     , e.extname
		     , null
		     , 'version ' || e.extversion || ' schema ' || n.nspname
		from pg_extension e
		join pg_namespace n on n.oid = e.extnamespace

		union all

		select 'Table'
		     , r.full_name
		     , r.nspname
		     , concat_ws(' '
		         , case when r.relkind = 'p' then 'partition by ' || pg_get_partkeydef(r.oid) end
		         , case when r.relispartition then 'partition of ' || p.parents || ' ' || pg_get_expr(r.relpartbound, r.oid) end
		         , case when not r.relispartition and p.parents is not null then 'inherits (' || p.parents || ')' end
		         , case when r.relpersistence = 'u' then 'unlogged' end
		         , case when r.relrowsecurity then 'row level security' end
		       )
		from rel r
		left join lateral (
			select string_agg(pn.nspname || '.' || pc.relname, ', ' order by i.inhseqno) as parents
			from pg_inherits i
			join pg_class pc on pc.oid = i.inhparent
			join pg_namespace pn on pn.oid = pc.relnamespace
			where i.inhrelid = r.oid
		) p on true
		where r.relkind in ('r', 'p')

		union all

		select 'Column'
		     , r.full_name || '.' || a.attname
		     , r.full_name
		     , concat_ws(' '
		         , format_type(a.atttypid, a.atttypmod)
		         , case when a.attcollation <> t.typcollation then 'collate ' || quote_ident(co.collname) end
		         , case a.attidentity
		               when 'a' then 'generated always as identity'
		               when 'd' then 'generated by default as identity'
		           end
		         , case when a.attidentity <> '' then '(start ' || s.seqstart || ' increment ' || s.seqincrement || ')' end
		         , case when a.attnotnull then 'not null' else 'null' end
		         , case
		               when a.attgenerated <> '' then 'generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ')' || case a.attgenerated when 's' then ' stored' else ' virtual' end
		               when ad.oid is not null then 'default ' || pg_get_expr(ad.adbin, ad.adrelid)
		           end
		       )
		from rel r
		join pg_attribute a on a.attrelid = r.oid
		join pg_type t on t.oid = a.atttypid
		left join pg_collation co on co.oid = a.attcollation
		left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
		left join lateral (
			-- the sequence of an identity column: its options, not its current value.
			select s.seqstart, s.seqincrement
			from pg_depend d
			join pg_sequence s on s.seqrelid = d.objid
			where d.classid = 'pg_class'::regclass
			  and d.refobjid = r.oid
			  and d.refobjsubid = a.attnum
			  and d.deptype = 'i'
		) s on true
		where r.relkind in ('r', 'p')
		  and a.attnum > 0
		  and not a.attisdropped

		union all

		select case co.contype
		           when 'p' then 'PrimaryKey'
		           when 'u' then 'UniqueConstraint'
		           when 'f' then 'ForeignKey'
		           when 'c' then 'CheckConstraint'
		           when 'x' then 'ExclusionConstraint'
		       end
		       -- a table has one primary key.
		     , case when co.contype = 'p' then r.full_name else r.full_name || '.' || co.conname end
		     , r.full_name
		     , case when co.contype = 'p' then 'constraint ' || co.conname || ' ' else '' end || pg_get_constraintdef(co.oid)
		from pg_constraint co
		join rel r on r.oid = co.conrelid
		where co.contype in ('p', 'u', 'f', 'c', 'x')

		union all

		-- the indexes of primary key, unique and exclusion constraints are compared as the constraints.
		select 'Index'
		     , r.full_name || '.' || ic.relname
		     , r.full_name
		     , pg_get_indexdef(i.indexrelid)
		from pg_index i
		join rel r on r.oid = i.indrelid
		join pg_class ic on ic.oid = i.indexrelid
		where not exists (
			select 1
			from pg_constraint co
			where co.conindid = i.indexrelid
			  and co.conrelid = i.indrelid
			  and co.contype in ('p', 'u', 'x')
		)

		union all

		select case r.relkind when 'v' then 'View' else 'MaterializedView' end
		     , r.full_name
		     , r.nspname
		     , pg_get_viewdef(r.oid, true) || coalesce(' with (' || array_to_string(r.reloptions, ', ') || ')', '')
		from rel r
		where r.relkind in ('v', 'm')

		union all

		select case p.prokind when 'p' then 'Procedure' else 'Function' end
		       -- functions are overloaded by their arguments.
		     , n.nspname || '.' || p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')'
		     , n.nspname
		     , case
		           when p.prokind = 'a' then concat_ws(', '
		               , 'aggregate (sfunc = ' || ag.aggtransfn::regproc
		               , 'stype = ' || format_type(ag.aggtranstype, null)
		               , 'finalfunc = ' || nullif(ag.aggfinalfn::oid, 0)::regproc
		               , 'initcond = ' || ag.agginitval
		             ) || ')'
		           else pg_get_functiondef(p.oid)
		       end
		from pg_proc p
		join nsp n on n.oid = p.pronamespace
		left join pg_aggregate ag on ag.aggfnoid = p.oid
		where not exists (select 1 from ext where ext.classid = 'pg_proc'::regclass and ext.objid = p.oid)

		union all

		select 'Trigger'
		     , r.full_name || '.' || t.tgname
		     , r.full_name
		     , pg_get_triggerdef(t.oid) || case t.tgenabled
		                                       when 'D' then ' disabled'
		                                       when 'R' then ' enabled replica'
		                                       when 'A' then ' enabled always'
		                                       else ''
		                                   end
		from pg_trigger t
		join rel r on r.oid = t.tgrelid
		where not t.tgisinternal

		union all

		-- event triggers have no schema.
		select 'Trigger'
		     , 'event.' || e.evtname
		     , null
		     , 'on ' || e.evtevent
		       || coalesce(' when tag in (' || array_to_string(e.evttags, ', ') || ')', '')
		       || ' execute function ' || e.evtfoid::regproc
		       || case e.evtenabled when 'D' then ' disabled' else '' end
		from pg_event_trigger e
		where not exists (select 1 from ext where ext.classid = 'pg_event_trigger'::regclass and ext.objid = e.oid)

		union all

		select 'Type'
		     , n.nspname || '.' || t.typname
		     , n.nspname
		     , case t.typtype
		           when 'e' then 'enum (' || (
		               select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder)
		               from pg_enum e
		               where e.enumtypid = t.oid
		             ) || ')'
		           when 'd' then concat_ws(' '
		               , 'domain ' || format_type(t.typbasetype, t.typtypmod)
		               , case when t.typnotnull then 'not null' end
		               , 'default ' || t.typdefault
		               , (
		                   select string_agg('constraint ' || c.conname || ' ' || pg_get_constraintdef(c.oid), ' ' order by c.conname)
		                   from pg_constraint c
		                   where c.contypid = t.oid
		                     and c.contype = 'c'
		                 )
		             )
		           when 'c' then '(' || (
		               select string_agg(a.attname || ' ' || format_type(a.atttypid, a.atttypmod), ', ' order by a.attnum)
		               from pg_attribute a
		               where a.attrelid = t.typrelid
		                 and a.attnum > 0
		                 and not a.attisdropped
		             ) || ')'
		           when 'r' then 'range (subtype = ' || (select format_type(rg.rngsubtype, null) from pg_range rg where rg.rngtypid = t.oid) || ')'
		       end
		from pg_type t
		join nsp n on n.oid = t.typnamespace
		-- enums, domains, ranges and composite types; the row type of a table is the table.
		where t.typtype in ('e', 'd', 'r', 'c')
		  and (t.typtype <> 'c' or exists (select 1 from pg_class c where c.oid = t.typrelid and c.relkind = 'c'))
		  and not exists (select 1 from ext where ext.classid = 'pg_type'::regclass and ext.objid = t.oid)

		union all

		-- the sequences of identity columns are compared as the columns.
		select 'Sequence'
		     , r.full_name
		     , r.nspname
		     , concat_ws(' '
		         , format_type(s.seqtypid, null)
		         , 'start ' || s.seqstart
		         , 'increment ' || s.seqincrement
		         , 'minvalue ' || s.seqmin
		         , 'maxvalue ' || s.seqmax
		         , 'cache ' || s.seqcache
		         , case when s.seqcycle then 'cycle' else 'no cycle' end
		         , (
		             select 'owned by ' || dn.nspname || '.' || dc.relname || '.' || da.attname
		             from pg_depend d
		             join pg_class dc on dc.oid = d.refobjid
		             join pg_namespace dn on dn.oid = dc.relnamespace
		             join pg_attribute da on da.attrelid = d.refobjid and da.attnum = d.refobjsubid
		             where d.classid = 'pg_class'::regclass
		               and d.objid = r.oid
		               and d.refclassid = 'pg_class'::regclass
		               and d.deptype = 'a'
		           )
		       )
		from rel r
		join pg_sequence s on s.seqrelid = r.oid
		where r.relkind = 'S'
		  and not exists (
			select 1
			from pg_depend d
			where d.classid = 'pg_class'::regclass
			  and d.objid = r.oid
			  and d.deptype = 'i'
		  )

		-- objects with one name are numbered in this order (SchemaSnapshot).
		order by object_type, object_name, definition
		""";

	/// <summary>
	/// PostgreSQL prints views in one form, but keeps the body of a function as written: compared without differences in whitespace.
	/// </summary>
	public static SchemaObject Normalize(SchemaObject obj)
		=> obj.Type is SchemaObjectType.View or SchemaObjectType.MaterializedView or SchemaObjectType.Procedure or SchemaObjectType.Function
			? obj with { Definition = SqlText.CollapseWhitespace(obj.Definition) }
			: obj;
}
